#!/usr/bin/env python3
"""Run a self-contained trial environment for manual end-to-end testing.

It creates a throwaway root key, starts the trial site on localhost, points the
desktop app at it, and optionally pre-consumes the trial quota so the "trial
ended" flow can be inspected.

    python tools/trial_demo.py                 # start the site only
    python tools/trial_demo.py --gui           # start the site and open the app
    python tools/trial_demo.py --exhaust --gui # 3 builds used up, show the dialog
    python tools/trial_demo.py --reset         # wipe demo keys, database and state

Everything lives under ``.pyshield-demo/`` (git ignored) and never touches the
real ``%APPDATA%\\PyShield`` state.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import threading
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from pyshield import license_admin, tool_license, trial_license, trial_server  # noqa: E402

DEMO_DIR = ROOT / ".pyshield-demo"
MARKER = ".pyshield-demo"


def _prepare(data_dir: Path) -> tuple[Path, Path]:
    data_dir.mkdir(parents=True, exist_ok=True)
    (data_dir / MARKER).write_text("generated by tools/trial_demo.py\n", encoding="utf-8")
    keys = data_dir / "root-keys"
    key_path = keys / "root.key"
    if not key_path.is_file():
        license_admin.generate_root(keys)
        print(f"[demo] root key created: {key_path}")
    return key_path, keys / "root.pub"


def _apply_trial(url: str, serial: str, machine: str) -> None:
    data = urllib.parse.urlencode({
        "serial": serial, "machine": machine, "edition": "trial",
    }).encode("utf-8")
    request = urllib.request.Request(
        url + "/trial/apply", data=data,
        headers={"Content-Type": "application/x-www-form-urlencoded"},
        method="POST",
    )
    with urllib.request.urlopen(request, timeout=10) as response:
        response.read()


def _exhaust(url: str) -> None:
    state = trial_license.install_state()
    _apply_trial(url, state["serial"], state["machine"])
    entitlement = trial_license.claim_and_apply(url)
    status = tool_license.check()
    for _ in range(int(entitlement.max_builds_per_month or 0)):
        tool_license.record_build(status)
    used = (status.quota or {}).get("used", "?")
    print(f"[demo] quota consumed: {used}/{entitlement.max_builds_per_month}")
    final = tool_license.check()
    print(f"[demo] license state: valid={final.valid} code={final.code} reason={final.reason}")


def main(argv: list[str] | None = None) -> int:
    try:
        sys.stdout.reconfigure(line_buffering=True)
    except (AttributeError, OSError):
        pass
    parser = argparse.ArgumentParser(prog="trial_demo", description="Local PyShield trial playground.")
    parser.add_argument("--data-dir", default=str(DEMO_DIR))
    parser.add_argument("--port", type=int, default=8090)
    parser.add_argument("--days", type=int, default=14)
    parser.add_argument("--builds", type=int, default=3)
    parser.add_argument("--reset", action="store_true", help="delete the demo directory first")
    parser.add_argument("--gui", action="store_true", help="launch the desktop app with the demo env")
    parser.add_argument("--open", action="store_true", help="open the application page in a browser")
    parser.add_argument("--exhaust", action="store_true", help="pre-consume the trial quota")
    args = parser.parse_args(argv)

    data_dir = Path(args.data_dir).expanduser().resolve()
    if args.reset and data_dir.exists():
        if not (data_dir / MARKER).is_file():
            print(f"[demo] refusing to delete {data_dir}: not a demo directory", file=sys.stderr)
            return 1
        shutil.rmtree(data_dir)
        print(f"[demo] removed {data_dir}")
        if not (args.gui or args.exhaust or args.open):
            return 0

    key_path, public_path = _prepare(data_dir)
    root_key = license_admin.load_root_key(key_path)

    home = data_dir / "home"
    home.mkdir(parents=True, exist_ok=True)
    url = f"http://127.0.0.1:{args.port}"
    os.environ[tool_license.ENV_HOME] = str(home)
    os.environ[tool_license.ENV_PUBLIC_KEY] = public_path.read_text(encoding="utf-8").strip()
    os.environ[trial_license.ENV_TRIAL_SERVER] = url
    os.environ["PYSHELD_TRIAL_DAYS"] = str(args.days)
    os.environ["PYSHELD_TRIAL_BUILDS"] = str(args.builds)
    os.environ.pop(tool_license.ENV_DEV, None)

    server = trial_server.create_server("127.0.0.1", args.port, root_key, data_dir / "trial")
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()

    state = trial_license.install_state()
    page = trial_license.handshake_url(url)
    print()
    print(f"[demo] site      {url}")
    print(f"[demo] serial    {state['serial']}")
    print(f"[demo] apply     {page}")
    print(f"[demo] state dir {home}")
    print(f"[demo] trial     {args.days} days / {args.builds} builds")
    print()

    if args.exhaust:
        _exhaust(url)

    if args.open:
        import webbrowser

        webbrowser.open(page)

    if args.gui:
        env = os.environ.copy()
        subprocess.Popen([sys.executable, "-m", "gui"], cwd=str(ROOT), env=env)
        print("[demo] desktop app launched")

    try:
        thread.join()
    except KeyboardInterrupt:
        print("\n[demo] stopping")
    finally:
        server.shutdown()
        server.server_close()
        server.store.close()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
