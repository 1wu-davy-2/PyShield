#!/usr/bin/env python3
"""Embed the runtime template into a generated Python module.

The builder needs the runtime sources at build time, but shipping them as
PyInstaller ``datas`` files puts every decryption routine in the released
``PyShieldBuilder.exe`` as plaintext. This script packs them into a compressed
blob that lives inside a compiled module instead. It is an exposure-reduction
measure, not a confidentiality boundary.

Run after changing anything under ``pyshield/runtime_template`` or the runtime
helpers (``crypto.py``, ``fingerprint.py``, ``ed25519.py``, ``secure_store.py``):

    python tools/embed_runtime.py

Use ``--check`` in CI to fail when the generated file is stale.
"""

from __future__ import annotations

import argparse
import base64
import io
import textwrap
import zipfile
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = ROOT / "pyshield" / "runtime_template" / "_shield_runtime"
OUTPUT = ROOT / "pyshield" / "_runtime_bundle.py"

# Bundle name -> source path. Names are relative to the generated
# ``_shield_runtime`` package so the builder can copy them directly.
SOURCES = {
    "__init__.py": TEMPLATE / "__init__.py",
    "__main__.py": TEMPLATE / "__main__.py",
    "_core.py": TEMPLATE / "_core.py",
    "_chacha_fast.pyx": TEMPLATE / "_chacha_fast.pyx",
    "_crypto.py": ROOT / "pyshield" / "crypto.py",
    "_machine.py": ROOT / "pyshield" / "fingerprint.py",
    "_ed25519.py": ROOT / "pyshield" / "ed25519.py",
    "_secure_store.py": ROOT / "pyshield" / "secure_store.py",
}

MODULE_TEMPLATE = '''\
"""Generated by tools/embed_runtime.py. Do not edit by hand.

The runtime sources are stored as a compressed blob so PyInstaller does not
ship them as plaintext data files. This raises static-analysis cost; it is not
a confidentiality boundary.
"""

from __future__ import annotations

import base64
import io
import zipfile
import zlib

BUNDLED_FILES = (
{names}
)

BLOB_B64 = (
{blob}
)


def load_files() -> dict[str, bytes]:
    """Return the embedded runtime files keyed by their output name."""
    archive = zlib.decompress(base64.b64decode(BLOB_B64))
    with zipfile.ZipFile(io.BytesIO(archive)) as bundle:
        names = set(bundle.namelist())
        missing = set(BUNDLED_FILES) - names
        if missing:
            raise RuntimeError("corrupted PyShield runtime bundle: " + ", ".join(sorted(missing)))
        return {{name: bundle.read(name) for name in BUNDLED_FILES}}
'''


def build_archive() -> bytes:
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
        for name, path in SOURCES.items():
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.create_system = 3
            info.external_attr = 0o644 << 16
            archive.writestr(info, path.read_bytes())
    return buffer.getvalue()


def render_module() -> str:
    compressed = zlib.compress(build_archive(), 9)
    encoded = base64.b64encode(compressed).decode("ascii")
    blob = "\n".join(f'    "{line}"' for line in textwrap.wrap(encoded, 100))
    names = "\n".join(f'    "{name}",' for name in SOURCES)
    return MODULE_TEMPLATE.format(names=names, blob=blob)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true",
        help="only verify that pyshield/_runtime_bundle.py is up to date",
    )
    args = parser.parse_args(argv)
    rendered = render_module()
    if args.check:
        try:
            current = OUTPUT.read_text(encoding="utf-8")
        except OSError as exc:
            print(f"runtime bundle is missing: {exc}")
            return 1
        if current != rendered:
            print(
                "pyshield/_runtime_bundle.py is stale; run "
                f"{Path(__file__).as_posix()} to regenerate it"
            )
            return 1
        print("runtime bundle is up to date")
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT} ({len(rendered)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
