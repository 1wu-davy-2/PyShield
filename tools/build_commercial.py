#!/usr/bin/env python3
"""Build the commercially licensed PyShield builder.

The tool public key is injected at packaging time so that the source tree and
CI are not tied to a single commercial deployment. The root private key is never
read by this script; only ``root.pub`` (or the Base85 public key itself).
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from pyshield import crypto  # noqa: E402

MODULE_PATH = ROOT / "pyshield" / "_tool_key.py"
APP_NAME = "PyShieldBuilder"
VERSION = "0.6.0.0"

MODULE_TEMPLATE = '''"""Auto-generated by tools/build_commercial.py. Do not commit.

The embedded key only verifies signed tool licenses. It cannot issue them.
"""

PUBLIC_KEY_B85 = "{public_key}"
'''


class BuildError(Exception):
    """Raised when a commercial packaging step fails."""


def _read_public_key(value: str) -> str:
    candidate = Path(value).expanduser()
    if candidate.is_file():
        text = candidate.read_text(encoding="utf-8").strip()
    else:
        text = value.strip()
    if not text:
        raise BuildError("the public key is empty")
    try:
        key = crypto.b85decode(text)
    except Exception as exc:
        raise BuildError("the public key is not valid Base85") from exc
    if len(key) != 32:
        raise BuildError("the public key must be a 32-byte Ed25519 public key")
    return crypto.b85encode(key)


def inject_public_key(value: str, module: Path = MODULE_PATH, force: bool = False) -> Path:
    encoded = _read_public_key(value)
    if module.exists() and not force:
        existing = module.read_text(encoding="utf-8")
        if f'PUBLIC_KEY_B85 = "{encoded}"' in existing:
            print(f"public key already injected: {module}")
            return module
        raise BuildError(f"{module} exists with a different key; pass --force to replace it")
    module.parent.mkdir(parents=True, exist_ok=True)
    module.write_text(
        MODULE_TEMPLATE.format(public_key=encoded),
        encoding="utf-8",
        newline="\n",
    )
    print(f"tool public key injected: {module}")
    return module


def find_output(candidates: list[Path]) -> Path | None:
    for path in candidates:
        if path.is_file():
            return path
    return None


def run(command: list[str], cwd: Path = ROOT) -> None:
    print("+ " + " ".join(command), flush=True)
    completed = subprocess.run(command, cwd=cwd)
    if completed.returncode != 0:
        raise BuildError(f"command failed with exit code {completed.returncode}")


def build_pyinstaller(clean: bool) -> Path | None:
    command = [sys.executable, "-m", "PyInstaller", "--noconfirm"]
    if clean:
        command.append("--clean")
    command.append("PyShieldBuilder.spec")
    run(command)
    suffix = ".exe" if sys.platform == "win32" else ""
    return find_output([ROOT / "dist" / f"{APP_NAME}{suffix}", ROOT / "dist" / APP_NAME])


def clean_runtime_template() -> None:
    template = ROOT / "pyshield" / "runtime_template"
    for cache in template.rglob("__pycache__"):
        shutil.rmtree(cache, ignore_errors=True)


def build_nuitka(clean: bool) -> Path | None:
    output_dir = ROOT / "dist-nuitka"
    if clean and output_dir.exists():
        shutil.rmtree(output_dir)
    command = [
        sys.executable, "-m", "nuitka",
        "--standalone",
        "--onefile",
        "--onefile-no-compression",
        "--assume-yes-for-downloads",
        "--jobs=4",
        "--include-package=pyshield",
        "--include-package=gui",
        "--nofollow-import-to=jinja2",
        "--nofollow-import-to=setuptools",
        "--nofollow-import-to=Cython",
        "--include-data-dir=gui/web=gui/web",
        "--include-data-dir=gui/assets=gui/assets",
        "--include-raw-dir=pyshield/runtime_template=pyshield/runtime_template",
        "--include-data-files=pyshield/crypto.py=pyshield/crypto.py",
        "--include-data-files=pyshield/fingerprint.py=pyshield/fingerprint.py",
        "--include-data-files=pyshield/ed25519.py=pyshield/ed25519.py",
        f"--output-dir={output_dir}",
        "--company-name=PyShield",
        "--product-name=PyShield Builder",
        f"--file-version={VERSION}",
        f"--product-version={VERSION}",
        "--copyright=Copyright (c) 2026 PyShield Authors. All rights reserved.",
    ]
    if sys.platform == "win32":
        command.extend([
            f"--output-filename={APP_NAME}.exe",
            "--windows-console-mode=disable",
            "--windows-icon-from-ico=gui/assets/icon.ico",
        ])
    else:
        command.extend([
            f"--output-filename={APP_NAME}",
        ])
    command.append("gui/main.py")
    run(command)
    suffix = ".exe" if sys.platform == "win32" else ""
    return find_output([output_dir / f"{APP_NAME}{suffix}", output_dir / APP_NAME])


def sign_binary(path: Path, signtool: str, timestamp_url: str) -> None:
    if not signtool:
        print("code signing skipped: pass --signtool to sign the executable")
        return
    command = [signtool, "sign", "/fd", "SHA256", "/td", "SHA256", "/tr", timestamp_url, "/a", str(path)]
    run(command)
    print(f"signed: {path}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="build_commercial",
        description="Inject the tool license public key and package PyShield.",
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    prepare = subparsers.add_parser("prepare", help="write pyshield/_tool_key.py")
    prepare.add_argument("--public-key", required=True, help="root.pub path or Base85 public key")
    prepare.add_argument("--module", default=str(MODULE_PATH))
    prepare.add_argument("--force", action="store_true")

    build = subparsers.add_parser("build", help="package the desktop builder")
    build.add_argument("--backend", choices=("pyinstaller", "nuitka"), default="pyinstaller")
    build.add_argument("--public-key", default="", help="inject this key before packaging")
    build.add_argument("--force-key", action="store_true", help="replace an existing _tool_key.py")
    build.add_argument("--no-clean", action="store_true", help="reuse previous build caches")
    build.add_argument("--signtool", default="", help="path to Windows signtool.exe")
    build.add_argument("--timestamp-url", default="http://timestamp.digicert.com")

    args = parser.parse_args(argv)
    try:
        if args.command == "prepare":
            inject_public_key(args.public_key, Path(args.module).expanduser(), args.force)
            print("The root private key must stay offline and never ship with the builder.")
            return 0
        if args.public_key:
            inject_public_key(args.public_key, MODULE_PATH, args.force_key)
        if not MODULE_PATH.is_file():
            raise BuildError(
                "pyshield/_tool_key.py is missing; pass --public-key or the packaged "
                "builder will run in development mode"
            )
        clean_runtime_template()
        binary = (
            build_nuitka(not args.no_clean)
            if args.backend == "nuitka"
            else build_pyinstaller(not args.no_clean)
        )
        if binary is None:
            raise BuildError("packaging finished but no executable was found")
        print(f"executable: {binary}")
        sign_binary(binary, args.signtool, args.timestamp_url)
        return 0
    except (BuildError, OSError) as exc:
        print(f"[build_commercial] ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
