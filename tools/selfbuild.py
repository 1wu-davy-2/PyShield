#!/usr/bin/env python3
"""Build a self-protected PyShieldBuilder executable (experimental).

The normal ``PyShieldBuilder.spec`` compiles the builder's own Python sources
directly into the PyInstaller PYZ. This script first runs PyShield over a
minimal copy of ``pyshield/`` and ``gui/``, then hands the stubs to
PyInstaller. The resulting exe keeps the builder's business logic encrypted
until the runtime decrypts it.

This is a cost-raising measure, not a confidentiality boundary: the runtime
master key and the builder's own ``pyshield.lic`` are still inside the exe.
Do not ship the intermediate protected directory; only the final exe is a
deliverable.

Usage:
    python tools/selfbuild.py
    python tools/selfbuild.py --stage-only --keep-work
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import importlib.util
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from pyshield import builder, crypto, licensing  # noqa: E402

DEFAULT_NAME = "PyShieldBuilder-selfbuild"
SPEC_NAME = "PyShieldBuilder.selfbuild.spec"
STUB_MARKER = "# PyShield protected module. Generated by pyshield; do not edit."

MANAGE_ENTRY = """\
\"\"\"Self-build entrypoint for the protected PyShieldBuilder (PoC).\"\"\"

from __future__ import annotations

import sys

from gui.main import main


if __name__ == "__main__":
    raise SystemExit(main())
"""


class SelfBuildError(RuntimeError):
    """Raised when the self-protected build cannot be completed."""


def _copy_ignore(directory: str, names: list[str]) -> set[str]:
    ignored: set[str] = set()
    base = Path(directory)
    for name in names:
        path = base / name
        if name in {"__pycache__", "runtime_template"}:
            ignored.add(name)
        elif name.endswith((".pyc", ".pyo", ".pyx", ".pyd", ".so")):
            ignored.add(name)
        elif name.endswith(licensing.SECRET_SUFFIX):
            ignored.add(name)
        elif path.is_dir() and (name.startswith(".") or name in {"build", "dist"}):
            ignored.add(name)
    return ignored


def prepare_staging(staging: Path) -> None:
    """Copy the minimum builder tree into a source project PyShield can build."""
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir(parents=True)

    for package in ("pyshield", "gui"):
        source = ROOT / package
        if not source.is_dir():
            raise SelfBuildError(f"missing source package: {source}")
        shutil.copytree(source, staging / package, ignore=_copy_ignore)

    bundle = staging / "pyshield" / "_runtime_bundle.py"
    if not bundle.is_file():
        raise SelfBuildError(
            "pyshield/_runtime_bundle.py is missing; run python tools/embed_runtime.py"
        )
    if (staging / "pyshield" / "runtime_template").exists():
        raise SelfBuildError("runtime_template must not be copied into the self-build staging tree")

    (staging / "manage.py").write_text(MANAGE_ENTRY, encoding="utf-8", newline="\n")


def collect_imports(staging: Path) -> list[str]:
    """Collect absolute imports that PyInstaller cannot see through stubs."""
    names: set[str] = set()
    for path in staging.rglob("*.py"):
        if "__pycache__" in path.parts:
            continue
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        except (OSError, SyntaxError, UnicodeDecodeError) as exc:
            raise SelfBuildError(f"cannot scan imports in {path}: {exc}") from exc
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    names.add(alias.name)
            elif isinstance(node, ast.ImportFrom):
                if node.level == 0 and node.module:
                    names.add(node.module)
    # Cython/setuptools are only used by the optional native-runtime path and
    # are excluded from the frozen builder. System.* are .NET namespaces
    # resolved by pythonnet, not Python modules.
    names = {name for name in names if name.split(".")[0] not in {"Cython", "setuptools", "System"}}
    if os.name != "nt":
        names = {
            name for name in names
            if name.split(".")[0] not in {"winreg", "clr", "clr_loader", "pythonnet"}
        }
    # sqlite3 backs the trial server and is a binary extension; add it even if
    # the scan changes in the future.
    names.add("sqlite3")
    return sorted(names)


def protect_project(staging: Path, protected: Path) -> builder.BuildResult:
    """Protect the staging project with PyShield's normal builder."""
    options = builder.BuildOptions(
        project=str(staging),
        output=str(protected),
        cipher="chacha-pure",
        runtime_source=True,
        integrity="off",
        no_verify=True,
        force=True,
    )
    return builder.build(options)


def _protected_python_files(protected: Path):
    for package in ("pyshield", "gui"):
        for path in (protected / package).rglob("*.py"):
            if "__pycache__" not in path.parts:
                yield path


def validate_protected(protected: Path) -> None:
    """Check that the protected tree is stubbed and its license is format 3."""
    required = (
        protected / "pyshield.lic",
        protected / "_shield_runtime" / "_core.py",
        protected / "manage.py",
    )
    for path in required:
        if not path.is_file():
            raise SelfBuildError(f"protected tree is missing {path}")

    if (protected / "pyshield" / "runtime_template").exists():
        raise SelfBuildError("runtime_template leaked into the protected tree")
    if any(protected.rglob("*" + licensing.SECRET_SUFFIX)):
        raise SelfBuildError("a build secret leaked into the protected tree")

    for path in _protected_python_files(protected):
        text = path.read_text(encoding="utf-8", errors="replace")
        if not text.startswith(STUB_MARKER):
            raise SelfBuildError(f"module was not protected: {path}")

    manage = (protected / "manage.py").read_text(encoding="utf-8", errors="replace")
    if not manage.startswith(STUB_MARKER):
        raise SelfBuildError("manage.py entrypoint was not protected")

    core = (protected / "_shield_runtime" / "_core.py").read_text(encoding="utf-8")
    if "__PYSHELD_" in core:
        raise SelfBuildError("runtime contains unresolved placeholders")

    secret_path = licensing.secret_path_for(protected)
    if not secret_path.is_file():
        raise SelfBuildError(f"build secret is missing: {secret_path}")
    secret = licensing.read_secret(secret_path)
    payload = licensing.open_license(
        crypto.b85decode(secret["master_key"]),
        secret["build_id"],
        (protected / "pyshield.lic").read_bytes(),
        licensing.secret_public_key(secret),
    )
    if payload.get("format") != licensing.FORMAT:
        raise SelfBuildError("self-protected build did not produce a format 3 license")
    if "build_key" in payload:
        raise SelfBuildError("self-protected license unexpectedly carries build_key")


def smoke_import(protected: Path, state_dir: Path) -> None:
    """Import a protected engine module outside the frozen exe."""
    state_dir.mkdir(parents=True, exist_ok=True)
    env = os.environ.copy()
    env["PYSHELD_LICENSE"] = str(protected / "pyshield.lic")
    env["PYSHELD_STATE_DIR"] = str(state_dir)
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env.pop("PYTHONPATH", None)
    code = "from pyshield import builder; print(builder.RUNTIME_PACKAGE)"
    completed = subprocess.run(
        [sys.executable, "-c", code],
        cwd=protected,
        env=env,
        capture_output=True,
        text=True,
    )
    if completed.returncode != 0:
        detail = (completed.stdout + completed.stderr).strip()
        raise SelfBuildError(f"protected modules could not be imported:\n{detail}")


def _require_pyinstaller() -> None:
    if importlib.util.find_spec("PyInstaller") is None:
        raise SelfBuildError(
            "PyInstaller is not installed; install pyinstaller==6.22.3 "
            "(and pywebview/pythonnet on Windows) before building the exe"
        )
    if importlib.util.find_spec("webview") is None:
        raise SelfBuildError("pywebview is not installed; install pywebview==6.2.1")


def build_executable(
    protected: Path,
    name: str,
    outdir: Path,
    work: Path,
    *,
    imports: list[str] | tuple[str, ...] = (),
    console: bool = False,
) -> Path:
    """Run PyInstaller against the protected tree and copy the artifact out."""
    _require_pyinstaller()
    source_spec = ROOT / SPEC_NAME
    if not source_spec.is_file():
        raise SelfBuildError(f"missing PyInstaller spec: {source_spec}")

    spec_copy = work / SPEC_NAME
    shutil.copy2(source_spec, spec_copy)
    imports_path = work / "selfbuild-imports.json"
    imports_path.write_text(
        json.dumps(sorted(set(imports))), encoding="utf-8", newline="\n"
    )
    dist_dir = work / "dist"
    build_dir = work / "build"

    env = os.environ.copy()
    env["PYSHELD_SELFBUILD_ROOT"] = str(protected)
    env["PYSHELD_SELFBUILD_REPO"] = str(ROOT)
    env["PYSHELD_SELFBUILD_NAME"] = name
    env["PYSHELD_SELFBUILD_IMPORTS"] = str(imports_path)
    if console:
        env["PYSHELD_SELFBUILD_CONSOLE"] = "1"
    command = [
        sys.executable,
        "-m",
        "PyInstaller",
        "--noconfirm",
        "--clean",
        "--distpath",
        str(dist_dir),
        "--workpath",
        str(build_dir),
        str(spec_copy),
    ]
    completed = subprocess.run(command, cwd=work, env=env)
    if completed.returncode != 0:
        raise SelfBuildError(f"PyInstaller failed with exit code {completed.returncode}")

    suffix = ".exe" if os.name == "nt" else ""
    built = dist_dir / f"{name}{suffix}"
    if not built.is_file():
        raise SelfBuildError(f"PyInstaller did not produce {built}")

    outdir.mkdir(parents=True, exist_ok=True)
    output = outdir / built.name
    shutil.copy2(built, output)
    digest = hashlib.sha256(output.read_bytes()).hexdigest()
    (outdir / f"SHA256SUMS-{name}.txt").write_text(
        f"{digest}  {output.name}\n", encoding="utf-8", newline="\n"
    )
    return output


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--outdir",
        default=str(ROOT / "dist-selfbuild"),
        help="directory for the final executable (default: dist-selfbuild)",
    )
    parser.add_argument(
        "--name",
        default=DEFAULT_NAME,
        help=f"executable name (default: {DEFAULT_NAME})",
    )
    parser.add_argument(
        "--workdir",
        default=None,
        help="empty directory for intermediate files (default: a temporary directory)",
    )
    parser.add_argument(
        "--keep-work",
        action="store_true",
        help="keep the intermediate protected tree (it contains runtime source and keys)",
    )
    parser.add_argument(
        "--stage-only",
        action="store_true",
        help="only prepare and validate the protected tree; do not run PyInstaller",
    )
    parser.add_argument(
        "--skip-smoke",
        action="store_true",
        help="skip the protected-import smoke test",
    )
    parser.add_argument(
        "--console",
        action="store_true",
        help="build a console executable so startup errors are visible",
    )
    args = parser.parse_args(argv)

    if args.workdir:
        work = Path(args.workdir).resolve()
        if work.exists() and any(work.iterdir()):
            print(f"workdir must be empty: {work}", file=sys.stderr)
            return 2
    else:
        work = Path(tempfile.mkdtemp(prefix="pyshield-selfbuild-"))
    work.mkdir(parents=True, exist_ok=True)
    keep_work = args.keep_work or args.stage_only

    try:
        staging = work / "staging"
        protected = work / "protected"
        prepare_staging(staging)
        imports = collect_imports(staging)
        result = protect_project(staging, protected)
        print(f"[selfbuild] {result.modules} modules protected")
        validate_protected(protected)
        # The build secret is only needed to reissue the self-license. Remove
        # it before PyInstaller so it can never be picked up as an artifact.
        licensing.secret_path_for(protected).unlink(missing_ok=True)

        if not args.skip_smoke:
            smoke_import(protected, work / "state")
            print("[selfbuild] protected modules import successfully")

        if args.stage_only:
            print(f"[selfbuild] protected tree: {protected}")
            print("[selfbuild] warning: keep this tree private; it contains runtime source")
            return 0

        output = build_executable(
            protected,
            args.name,
            Path(args.outdir).resolve(),
            work,
            imports=imports,
            console=args.console,
        )
        print(f"[selfbuild] executable: {output}")
        print("[selfbuild] warning: runtime master key and self-license are inside the exe")
        return 0
    except (SelfBuildError, builder.BuildError, OSError) as exc:
        print(f"[selfbuild] failed: {exc}", file=sys.stderr)
        return 1
    finally:
        if keep_work:
            print(f"[selfbuild] work directory kept: {work}")
        else:
            shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    raise SystemExit(main())
